from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
f=TTFont("fonts/DSEG14Classic-Bold.ttf")
gs=f.getGlyphSet(); cmap=f.getBestCmap()
def contours(ch):
    p=DecomposingRecordingPen(gs); gs[cmap[ord(ch)]].draw(p)
    out=[];cur=[]
    for op,args in p.value:
        if op=="moveTo": cur=[args[0]]
        elif op=="lineTo": cur.append(args[0])
        elif op in("closePath","endPath"): out.append(cur)
    return out
def simplify(pts):
    pts=[p for i,p in enumerate(pts) if p!=pts[i-1]]
    changed=True
    while changed:
        changed=False
        for i in range(len(pts)):
            a,b,c=pts[i-1],pts[i],pts[(i+1)%len(pts)]
            if (b[0]-a[0])*(c[1]-b[1])-(b[1]-a[1])*(c[0]-b[0])==0:
                pts.pop(i);changed=True;break
    return pts
chars="ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
X0,X1=99,717
def norm(pts):
    return tuple(((x-X0)*1000//(X1-X0), 1000-y) for x,y in pts)
lib=[];index={}
def seg(pts):
    k=norm(simplify(pts))
    if k not in index: index[k]=len(lib);lib.append(k)
    return index[k]
masks=[]
for ch in chars:
    m=0
    for c in contours(ch): m|=1<<seg(c)
    masks.append(m)
# DSEG draws S with two extra diagonals and 0 with a slash; use the plain 5 and O shapes instead
masks[chars.index('S')]=masks[chars.index('5')]
masks[chars.index('0')]=masks[chars.index('O')]
allm=0
for c in contours('~'): allm|=1<<seg(c)
print("unique segs",len(lib), "maxpts",max(len(s) for s in lib))
xs=[x for s in lib for x,_ in s]; print("x range",min(xs),max(xs))
n=len(lib)
o=["// 14-segment letters and digits traced from DSEG14 Classic Bold (SIL OFL 1.1, Keshikan),",
   "// converted to polygons in a 0..1000 box (generated by a script; see LICENSES/).","#pragma once","#include <stdint.h>","",
   "#define SEG14_N %d"%n,"#define SEG14_ASPECT 618   // glyph width / height, in thousandths","",
   'static const char SEG14_CHARS[] = "%s";'%chars,"",
   "static const int16_t SEG14_POLYS[SEG14_N][%d][2] = {"%max(len(s) for s in lib)]
for s in lib:
    o.append("  {"+",".join("{%d,%d}"%p for p in s)+"},")
o.append("};")
o.append("static const uint8_t SEG14_LEN[SEG14_N] = {"+",".join(str(len(s)) for s in lib)+"};")
o.append("static const uint32_t SEG14_MASK[] = {"+",".join("0x%XU"%m for m in masks)+"};")
o.append("#define SEG14_ALL 0x%XU"%allm)
open("src/c/seg14.h","w").write("\n".join(o)+"\n")

